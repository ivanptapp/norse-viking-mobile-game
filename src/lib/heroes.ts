export function stageInfo(stageId: number) {
  const chapterIdx = Math.floor((stageId - 1) / STAGES_PER_CHAPTER);
  const within = (stageId - 1) % STAGES_PER_CHAPTER;
  const chapter = CHAPTERS[Math.min(chapterIdx, CHAPTERS.length - 1)];
  const isBoss = within === STAGES_PER_CHAPTER - 1;
  const pool = ENEMY_POOLS[Math.min(chapterIdx, ENEMY_POOLS.length - 1)];
  const enemies = Array.from({ length: isBoss ? 5 : 3 + (within % 3) }, (_, i) => pool[(i + within) % pool.length]);
  const enemyLevel = 1 + Math.floor((stageId - 1) * 1.15);
  const scale = (isBoss ? 1.18 : 1) * (0.82 + stageId * 0.028);
  const storyBeat = CAMPAIGN_STORIES[chapterIdx]?.[within];
  return {
    stageId,
    chapter,
    within: within + 1,
    stageName: storyBeat?.title ?? `${chapter.name} · Etapa ${within + 1}`,
    story: storyBeat?.story ?? chapter.desc,
    isBoss,
    enemies,
    enemyLevel,
    scale,
    rewards: {
      gold: 180 + stageId * 65 + (isBoss ? 500 : 0),
      exp: 30 + stageId * 14 + (isBoss ? 90 : 0),
      gems: isBoss ? 60 : stageId % 4 === 0 ? 15 : 0,
    },
    energyCost: 6,
  };
}

export function towerInfo(floor: number) {
  const pools = ENEMY_POOLS.flat();
  const enemies = Array.from({ length: 5 }, (_, i) => pools[(floor * 2 + i * 3) % pools.length]);
  return {
    floor,
    enemies,
    enemyLevel: 2 + floor,
    scale: 0.8 + floor * 0.055,
    rewards: {
      gold: 250 + floor * 80,
      exp: 25 + floor * 8,
      gems: floor % 5 === 0 ? 80 : 12,
    },
  };
}

