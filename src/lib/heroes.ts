export function heroStats(def: HeroDef, level: number, stars: number) {
  const lvMult = 1 + (level - 1) * 0.09;
  const starMult = 1 + (stars - 2) * 0.22;
  const m = lvMult * starMult;
  return {
    hp: Math.round(def.hp * m),
    atk: Math.round(def.atk * m),
    def: Math.round(def.def * m),
    spd: def.spd,
    crit: def.crit + (stars - 2),
    power: Math.round((def.hp / 12) * m + def.atk * 4.2 * m + def.def * 2.4 * m + def.spd * 1.5),
  };
}

